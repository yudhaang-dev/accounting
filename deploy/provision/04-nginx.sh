#!/usr/bin/env bash
# Stage D: nginx vhosts for the two domains, behind Cloudflare. A failed `nginx -t` removes what this stage added and stops.
set -euo pipefail

SNIP=/etc/nginx/snippets/cloudflare-realip.conf
added=()

echo "== Cloudflare ranges"
v4=$(curl -fsS --max-time 20 https://www.cloudflare.com/ips-v4)
v6=$(curl -fsS --max-time 20 https://www.cloudflare.com/ips-v6)
[ -n "$v4" ] && [ -n "$v6" ] || { echo "Cloudflare range lists are empty; stopping." >&2; exit 1; }
{
    echo "# The real client address comes from Cloudflare's header, trusted only from Cloudflare's own ranges. Regenerated by provisioning."
    for r in $v4 $v6; do echo "set_real_ip_from $r;"; done
    echo "real_ip_header CF-Connecting-IP;"
    echo "real_ip_recursive on;"
} > "$SNIP"
added+=("$SNIP")

echo "== placeholder certificate and ACME webroot"
install -d -m 0755 /var/www/letsencrypt
if [ ! -f /etc/nginx/ssl-placeholder.crt ]; then
    openssl req -x509 -nodes -newkey rsa:2048 -days 90 -subj "/CN=placeholder.invalid" \
        -keyout /etc/nginx/ssl-placeholder.key -out /etc/nginx/ssl-placeholder.crt 2>/dev/null
    chmod 600 /etc/nginx/ssl-placeholder.key
fi

vhost() {
    local name=$1 domain=$2 sock=$3 file=/etc/nginx/sites-available/$1
    cat > "$file" <<CONF
# ${domain}: Laravel API and SPA behind Cloudflare. Certificate lines are switched to Let's Encrypt by stage E.
server {
    listen 80;
    listen [::]:80;
    server_name ${domain};

    location /.well-known/acme-challenge/ { root /var/www/letsencrypt; }
    location / { return 301 https://\$host\$request_uri; }
}

server {
    listen 443 ssl http2;
    listen [::]:443 ssl http2;
    server_name ${domain};

    ssl_certificate /etc/nginx/ssl-placeholder.crt;
    ssl_certificate_key /etc/nginx/ssl-placeholder.key;
    ssl_protocols TLSv1.2 TLSv1.3;

    include snippets/cloudflare-realip.conf;

    root /var/www/${name}/current/public;
    index index.php index.html;
    client_max_body_size 16m;

    access_log /var/log/nginx/${name}.access.log;
    error_log /var/log/nginx/${name}.error.log;

    location /.well-known/acme-challenge/ { root /var/www/letsencrypt; }

    location / { try_files \$uri \$uri/ /index.php?\$query_string; }

    location ~ ^/index\.php(/|\$) {
        include fastcgi_params;
        fastcgi_pass unix:/run/php/${sock}-fpm.sock;
        fastcgi_param SCRIPT_FILENAME \$realpath_root\$fastcgi_script_name;
        fastcgi_param DOCUMENT_ROOT \$realpath_root;
        fastcgi_hide_header X-Powered-By;
        fastcgi_read_timeout 120s;
    }

    # No other PHP file and no dotfile is ever served.
    location ~ \.php\$ { return 404; }
    location ~ /\.(?!well-known) { deny all; }
}
CONF
    ln -sfn "$file" "/etc/nginx/sites-enabled/$name"
    added+=("$file" "/etc/nginx/sites-enabled/$name")
}

vhost accounting accounting.vcare.web.id accounting
vhost accounting-staging staging-accounting.vcare.web.id accounting-staging

if ! nginx -t 2>&1 | tail -3; then
    rm -f "${added[@]}"
    echo "nginx -t failed: this stage's files are removed, nothing reloaded." >&2
    exit 1
fi

systemctl reload nginx
sleep 1
systemctl is-active nginx

echo "== checks (through nginx on this machine)"
for h in accounting.vcare.web.id staging-accounting.vcare.web.id; do
    curl -sk -o /dev/null -w "$h https: %{http_code}\n" --resolve "$h:443:127.0.0.1" "https://$h/"
    curl -s -o /dev/null -w "$h http : %{http_code} -> %{redirect_url}\n" --resolve "$h:80:127.0.0.1" "http://$h/"
done
curl -sk -o /dev/null -w "php file blocked: %{http_code}\n" --resolve "accounting.vcare.web.id:443:127.0.0.1" "https://accounting.vcare.web.id/x.php"
curl -sk -o /dev/null -w "ipm https: %{http_code}\n" --resolve ipm.vcare.web.id:443:127.0.0.1 https://ipm.vcare.web.id/
